#!/usr/bin/env python3
"""Inventory protected external inputs without changing their bytes."""

from __future__ import annotations

import hashlib
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "ASSET_MANIFEST.md"


def configured_data_dir() -> Path:
    configured = os.environ.get("VIRIDEXA_DATA_DIR")
    if not configured:
        env_file = ROOT / ".env"
        if env_file.exists():
            for line in env_file.read_text().splitlines():
                if line.startswith("VIRIDEXA_DATA_DIR="):
                    configured = line.split("=", 1)[1].strip()
                    break
    path = Path(configured) if configured else ROOT.parent / "VIRIDEXA-protected" / "data"
    return (ROOT / path).resolve() if not path.is_absolute() else path.resolve()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> None:
    data_dir = configured_data_dir()
    database_archive = data_dir.parent / "database"
    if not data_dir.is_dir() or not database_archive.is_dir():
        raise SystemExit(f"Protected input directories missing: {data_dir} and {database_archive}")

    files: list[tuple[str, Path]] = []
    for label, base in (("data", data_dir), ("database", database_archive)):
        for path in base.rglob("*"):
            if not path.is_file():
                continue
            relative = path.relative_to(base).as_posix()
            if relative.startswith(("processed/", "migration/")):
                continue
            files.append((f"{label}/{relative}", path))

    rows = []
    total_bytes = 0
    for logical_path, path in sorted(files):
        size = path.stat().st_size
        total_bytes += size
        original = ""
        if logical_path == "data/raw/course/课程设计资料.pdf":
            original_path = Path.home() / "Downloads" / "课程设计资料.pdf"
            if original_path.is_file():
                if sha256(original_path) != sha256(path):
                    raise SystemExit("Course PDF source and protected copy no longer match.")
                original = str(original_path)
        rows.append((logical_path, str(path.resolve()), size, sha256(path), original))

    lines = [
        "# Protected asset manifest",
        "",
        "Generated by `scripts/build_asset_manifest.py`. SHA-256 is computed from file bytes in 1 MiB blocks.",
        "Inputs are read from `VIRIDEXA_DATA_DIR` outside the Git worktree; the archived source database files are in its sibling `database/` directory.",
        "Pipeline outputs under `processed/` and the non-scientific migration note are excluded.",
        "",
        f"- Files: **{len(rows)}**",
        f"- Total bytes: **{total_bytes:,}**",
        "- No source files are modified by this inventory.",
        "",
        "| Logical path | Absolute protected path | Size (bytes) | SHA-256 | Original source path when copied |",
        "|---|---|---:|---|---|",
    ]
    for logical, absolute, size, digest, original in rows:
        cells = [logical.replace("|", "\\|"), absolute.replace("|", "\\|"), f"{size:,}", digest, original.replace("|", "\\|")]
        lines.append("| " + " | ".join(cells) + " |")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(rows)} protected files, {total_bytes:,} bytes")


if __name__ == "__main__":
    main()
