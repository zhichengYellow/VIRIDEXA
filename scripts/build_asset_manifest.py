#!/usr/bin/env python3
"""Hash every file in the preserved legacy data and SQL trees."""

from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "LEGACY_ASSET_MANIFEST.md"
EXTERNAL_COURSE_PDF = Path("/Users/binyellow/Downloads/课程设计资料.pdf")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> None:
    paths = {ROOT / ".DS_Store"}
    for dirname in ("data", "database"):
        base = ROOT / dirname
        if base.exists():
            paths.update(
                path for path in base.rglob("*")
                if path.is_file() and "data/migration/" not in path.relative_to(ROOT).as_posix()
            )

    rows = []
    total_bytes = 0
    for path in sorted(paths, key=lambda item: item.relative_to(ROOT).as_posix()):
        relative = path.relative_to(ROOT).as_posix()
        size = path.stat().st_size
        total_bytes += size
        origin = ""
        if relative == "data/raw/course/课程设计资料.pdf" and EXTERNAL_COURSE_PDF.is_file():
            if sha256(EXTERNAL_COURSE_PDF) != sha256(path):
                raise SystemExit("Course PDF source and protected copy no longer match.")
            origin = str(EXTERNAL_COURSE_PDF)
        rows.append((relative, str(path), size, sha256(path), origin))

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Legacy asset manifest",
        "",
        "Generated by `scripts/build_asset_manifest.py`. SHA-256 is computed from file bytes in 1 MiB blocks.",
        "The inventory covers the existing `data/` and `database/` trees plus the workspace metadata file. No source bytes are changed by this script.",
        "",
        f"- Files: **{len(rows)}**",
        f"- Total bytes: **{total_bytes:,}**",
        "- The course PDF was copied without replacement from the Downloads path shown on its row; both copies are checked for identical SHA-256 on each manifest run.",
        "- `.DS_Store` rows are filesystem metadata, included so the byte inventory is complete; they are not scientific records.",
        "",
        "| Relative path | Absolute inventory path | Size (bytes) | SHA-256 | Original source path when copied |",
        "|---|---|---:|---|---|",
    ]
    for relative, absolute, size, digest, origin in rows:
        cells = [relative.replace("|", "\\|"), absolute.replace("|", "\\|"), f"{size:,}", digest, origin.replace("|", "\\|")]
        lines.append("| " + " | ".join(cells) + " |")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(rows)} files, {total_bytes:,} bytes")


if __name__ == "__main__":
    main()
